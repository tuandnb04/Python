# Tổng quan về Python:
# - Ngôn ngữ lập trình bậc cao, đa năng (general-purpose), cú pháp đơn giản và trong sáng.

# Cài đặt và Môi trường (Installation & Environment):
# - Tải từ trang chủ chính thức: https://www.python.org/ (Windows, macOS, Linux)
# - Terminal: Giao diện dạng văn bản (text-based interface) dùng để nhập và thực thi các câu lệnh
# - Kiểm tra phiên bản: python --version (hoặc python3 --version)

# Trình thông dịch & Interactive Shell (REPL):
# - Interactive Shell: Chương trình cho phép nhập từng lệnh một và xem kết quả tức thì
# - Khởi động Shell từ Terminal: Gõ 'python' (hoặc 'python3') rồi nhấn Enter
# - Dấu nhắc lệnh '>>>': Báo hiệu Python đang sẵn sàng chờ người dùng nhập lệnh (waiting for user input)
# - Chu trình REPL: Read (Đọc) -> Evaluate (Thực thi) -> Print (In kết quả) -> Loop (Lặp lại)
# - Thoát Shell: gõ exit() hoặc nhấn Ctrl + Z + Enter (Windows) / Ctrl + D (macOS/Linux)

# Trình soạn thảo & IDE (Integrated Development Environment - Môi trường phát triển tích hợp):
# - IDE/Editor phổ biến: VS Code, PyCharm, Spyder (Lưu ý: Clang là trình biên dịch C/C++, không phải IDE Python)
# - Chạy file script Python qua Terminal: python main.py (hoặc python3 main.py)

# Các lĩnh vực ứng dụng và thư viện/framework phổ biến:
# - Data Analysis: Pandas, NumPy
# - Machine Learning & AI: TensorFlow, Scikit-learn, PyTorch
# - Web Development: Django, FastAPI, Flask (Instagram, Pinterest)
# - Cybersecurity & Ethical Hacking: Quét lỗ hổng, phân tích mã độc, kiểm thử an ninh tự động
# - Embedded Systems & IoT: Raspberry Pi, MicroPython (Smart home, cảm biến)
# - Automation & Scraping: Selenium, BeautifulSoup (Tự động hóa tác vụ văn phòng, cào dữ liệu web)
# - Testing & DevOps: pytest, CI/CD scripts, giám sát server và log hệ thống

